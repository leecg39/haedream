/**
 * data/egg_pages.db(fit.rfenms.com 수집 결과)를 읽어 앱에서 바로 import 가능한
 * MockDB 모듈(src/lib/fit-mock-db.ts)을 생성한다.
 *
 * - html 원문은 용량이 커서 제외한다.
 * - text_content 는 페이지당 최대 900자 수준이라 전문을 담는다.
 *   원본 화면의 실제 라벨/표 머리글이 그대로 들어 있어 UI 문구의 근거가 된다.
 *
 * 실행: node scripts/build-fit-mock-db.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const DB_PATH = path.join(ROOT, 'data', 'egg_pages.db');
const SUMMARY_PATH = path.join(ROOT, 'data', 'egg-fetch-summary.json');
const OUT_PATH = path.join(ROOT, 'src', 'lib', 'fit-mock-db.ts');

/** page_file → 클론 라우트. include/* 는 라우트가 없어 null. */
const ROUTE_BY_FILE = {
  'stat.html': '/fit/stat',
  'firm.html': '/fit/firm',
  'research.html': '/fit/research',
  'peak.html': '/fit/peak',
  'peakPanel.html': '/fit/peak-panel',
  'peakSet.html': '/fit/peak-set',
  'peakHis.html': '/fit/peak-his',
  'powerUsage.html': '/fit/power-usage',
  'peakUsage.html': '/fit/peak-usage',
  'controlHis.html': '/fit/control-his',
  'acp.html': '/fit/acp',
  'ratePlan.html': '/fit/rate-plan',
  'reduce.html': '/fit/reduce',
  'report.html': '/fit/report',
  'login.html': '/fit/login',
};

function readDb() {
  const db = new DatabaseSync(DB_PATH, { readOnly: true });

  try {
    const categories = db
      .prepare('SELECT id, ord, name, disabled FROM categories ORDER BY ord')
      .all()
      .map((c) => ({ id: c.id, ord: c.ord, name: c.name, disabled: !!c.disabled }));

    const pages = db
      .prepare(
        `SELECT p.id, p.category_id, p.menu_name, p.page_file, p.url,
                p.http_status, p.final_url, p.title, p.content_length,
                p.styles, p.scripts, p.text_content, p.fetched_at
         FROM pages p JOIN categories c ON c.id = p.category_id
         ORDER BY c.ord, p.id`,
      )
      .all()
      .map((p) => ({
        id: p.id,
        categoryId: p.category_id,
        menuName: p.menu_name,
        pageFile: p.page_file,
        url: p.url,
        route: ROUTE_BY_FILE[p.page_file] ?? null,
        httpStatus: p.http_status ?? 0,
        finalUrl: p.final_url ?? '',
        title: p.title ?? '',
        contentLength: p.content_length ?? 0,
        styles: JSON.parse(p.styles || '[]'),
        scripts: JSON.parse(p.scripts || '[]'),
        textContent: p.text_content ?? '',
        fetchedAt: p.fetched_at,
      }));

    return { categories, pages };
  } finally {
    db.close();
  }
}

let data;

try {
  data = readDb();
} catch (error) {
  console.error('egg_pages.db 를 읽지 못했습니다:', error);
  throw new Error(`MockDB 생성 실패: ${DB_PATH} 를 읽을 수 없습니다.`);
}

const summary = JSON.parse(readFileSync(SUMMARY_PATH, 'utf8'));
const { categories, pages } = data;

const body = `/**
 * AUTO-GENERATED by scripts/build-fit-mock-db.mjs — 직접 수정하지 말 것.
 * 원본: data/egg_pages.db (${summary.site}, ${summary.fetchedAt})
 * 재생성: node scripts/build-fit-mock-db.mjs
 */

export interface FitMockCategory {
  readonly id: number;
  readonly ord: number;
  readonly name: string;
  readonly disabled: boolean;
}

export interface FitMockPage {
  readonly id: number;
  readonly categoryId: number;
  readonly menuName: string;
  readonly pageFile: string;
  readonly url: string;
  /** 클론 라우트. include/* 파샬은 라우트가 없어 null. */
  readonly route: string | null;
  readonly httpStatus: number;
  readonly finalUrl: string;
  readonly title: string;
  readonly contentLength: number;
  readonly styles: readonly string[];
  readonly scripts: readonly string[];
  /** 원본 화면의 실제 노출 텍스트 전문 (비인증 수집이라 값은 비어 있고 라벨만 있다) */
  readonly textContent: string;
  readonly fetchedAt: string;
}

export interface FitMockFetchSummary {
  readonly site: string;
  readonly categories: number;
  readonly pagesTotal: number;
  readonly pagesOk: number;
  readonly failures: readonly string[];
  readonly fetchedAt: string;
}

export const FIT_MOCK_FETCH_SUMMARY: FitMockFetchSummary = ${JSON.stringify(
  {
    site: summary.site,
    categories: summary.categories,
    pagesTotal: summary.pagesTotal,
    pagesOk: summary.pagesOk,
    failures: summary.failures,
    fetchedAt: summary.fetchedAt,
  },
  null,
  2,
)};

export const FIT_MOCK_CATEGORIES: readonly FitMockCategory[] = ${JSON.stringify(categories, null, 2)};

export const FIT_MOCK_PAGES: readonly FitMockPage[] = ${JSON.stringify(pages, null, 2)};

/** 라우트가 있는 페이지만 (include 파샬 제외) */
export const FIT_MOCK_ROUTED_PAGES: readonly FitMockPage[] = FIT_MOCK_PAGES.filter(
  (page) => page.route !== null,
);

export function findFitMockPage(pageFile: string): FitMockPage | undefined {
  return FIT_MOCK_PAGES.find((page) => page.pageFile === pageFile);
}

export function findFitMockPageByRoute(route: string): FitMockPage | undefined {
  return FIT_MOCK_PAGES.find((page) => page.route === route);
}
`;

writeFileSync(OUT_PATH, body, 'utf8');
console.log(
  `생성 완료: ${path.relative(ROOT, OUT_PATH)} — 카테고리 ${categories.length}개, 페이지 ${pages.length}개`,
);
